/**
 * ============================================================
 *  合成游戏 · 素材与规则配置
 * ============================================================
 *
 *  ★ 换图只改这个文件（或者干脆只覆盖图片，连这个文件都不用动）。
 *
 *  一个 theme（主题）= 一条"合成链"：
 *     最低级 → 次低级 → …… → 最高级
 *  两个相同等级的东西撞在一起，就会合成为下一级。
 *  两个最高级撞在一起 → 一起消失，给双倍大分。
 *
 *  当前是【4 级】配置，图片在 assets/theme/01.png ~ 04.png。
 *
 *  每个等级对象：
 *    name   —— 名字（图片加载失败时用它兜底显示）
 *    image  —— 图片路径，相对 index.html
 *    radius —— 半径（游戏内逻辑像素，不是图片真实尺寸），必须从小到大递增
 *    score  —— 合成到这一级时加的分
 *    color  —— 主题色（粒子特效 / 图片缺失时的兜底色块）
 *
 *  === 换图最快的办法 ===
 *    把你的 4 张图命名为 01.png 02.png 03.png 04.png，
 *    直接覆盖 assets/theme/ 里的同名文件，刷新页面即可，不用改代码。
 *
 *  === 想改等级数量 / 名字 / 大小 ===
 *    直接增删下面 levels 数组项，代码会自适应。
 *    注意 spawnRange：4 级时填 1（只出最小两级），等级越多可以调到 2~3。
 * ============================================================
 */

window.GAME_CONFIG = {
  // 页面标题
  title: '合成大海肠',

  // 打开页面时用哪套主题
  defaultTheme: 'main',

  // 画布逻辑尺寸（会自动等比缩放到屏幕，不用改）
  canvas: { width: 480, height: 720 },

  // 顶部死亡线的高度（越小越难）
  deadlineY: 132,

  // 每次掉落时随机出 0 ~ spawnRange 级（0 = 最低级）
  // 4 级链填 1：只出第 1、2 级，才合得动
  spawnRange: 1,

  // 两次掉落的最小间隔（毫秒）
  dropInterval: 300,

  // ================= 主题 =================
  themes: {
    main: {
      name: '海肠',
      levels: [
        { name: '一级', image: 'assets/theme/05.png', radius: 24, score: 1,  color: '#4a90d9' },
        { name: '二级', image: 'assets/theme/06.png', radius: 38, score: 4,  color: '#5cb85c' },
        { name: '三级', image: 'assets/theme/07.png', radius: 56, score: 12, color: '#f0a030' },
        { name: '四级', image: 'assets/theme/08.png', radius: 78, score: 30, color: '#d9534f' },
      ],
    },
  },
};
